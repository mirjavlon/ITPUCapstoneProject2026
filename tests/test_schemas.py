"""Schema / Pydantic validation tests."""

import pytest
from pydantic import ValidationError

from app.schemas.user import UserCreate
from app.schemas.tournament import TournamentCreate, TournamentUpdate, TournamentStatusUpdate
from app.schemas.team import TeamCreate, TeamUpdate
from app.schemas.match import MatchCreate, MatchScoreUpdate, MatchResultWithdraw, GoalEventCreate
from app.schemas.player import PlayerCreate


# =====================================================================
# User schemas
# =====================================================================

class TestUserSchemas:
    def test_valid_user_create(self):
        u = UserCreate(username="alice", email="alice@example.com", password="Secret123", account_type="manager")
        assert u.username == "alice"

    def test_username_too_short(self):
        with pytest.raises(ValidationError):
            UserCreate(username="ab", email="a@b.com", password="Secret123", account_type="manager")

    def test_username_invalid_chars(self):
        with pytest.raises(ValidationError):
            UserCreate(username="no spaces!", email="a@b.com", password="Secret123", account_type="manager")

    def test_password_too_short(self):
        with pytest.raises(ValidationError):
            UserCreate(username="user", email="a@b.com", password="short", account_type="manager")

    def test_extra_fields_rejected(self):
        with pytest.raises(ValidationError):
            UserCreate(username="user", email="a@b.com", password="Secret123", account_type="manager", is_admin=True)

    def test_invalid_account_type(self):
        with pytest.raises(ValidationError):
            UserCreate(username="user", email="a@b.com", password="Secret123", account_type="admin")


