# Match schemas
# =====================================================================

class TestMatchSchemas:
    def test_match_date_requires_timezone(self):
        with pytest.raises(ValidationError):
            MatchCreate(
                tournament_id=1, home_team_id=1, away_team_id=2,
                match_date="2026-10-01T10:00:00",  # no timezone
            )

    def test_valid_match_create(self):
        m = MatchCreate(
            tournament_id=1, home_team_id=1, away_team_id=2,
            match_date="2026-10-01T10:00:00+05:00",
        )
        assert m.venue is None

    def test_score_update_negative_score_rejected(self):
        with pytest.raises(ValidationError):
            MatchScoreUpdate(home_score=-1, away_score=0, expected_version=1)

    def test_withdraw_requires_reason(self):
        with pytest.raises(ValidationError):
            MatchResultWithdraw(expected_version=1, reason="ab")  # too short

    def test_goal_event_minute_range(self):
        with pytest.raises(ValidationError):
            GoalEventCreate(scorer_id=1, minute=0)  # min is 1
        with pytest.raises(ValidationError):
            GoalEventCreate(scorer_id=1, minute=121)  # max is 120
        event = GoalEventCreate(scorer_id=1, minute=90)
        assert event.minute == 90


